/**
 * Renders docs/seo/service-pages/*.md from the typed specs and the workbook-derived data, so the documents
 * cannot drift from what the tests check. Run `node --import ./tests/register.mjs scripts/seo/build-service-docs.mjs`.
 * architecture is hand-written (docs/seo/service-pages/page-architecture.md) and not produced here.
 */

const GEOS = ["Kenya", "Nairobi", "Nakuru", "Rongo", "Migori"] as const
const esc = (t: string) => t.replace(/\|/g, "\\|")
/**
 * Terms that name an offering or setting the existing site copy does not state. A keyword containing one is a
 * topic only if the page's service-specific evidence items confirm that offering. Judgment rule, listed in the briefs.
 */
export const SCOPE_TERMS = /\b(maintenance|repair|monitoring|surveillance|patrol|night|outsourced|access control|crowd control|bodyguard|executive|personal|intruder|concert|wedding|festival|conference|industrial|warehouse|apartment)\b/i
const pad = (n: number) => String(n).padStart(2, "0")
const slugOf = (b: ServiceBrief) => b.path.split("/").filter(Boolean).pop()!
export const briefFileName = (b: ServiceBrief) => `briefs/${pad(b.rank)}-${slugOf(b)}.md`
const noSlash = (p: string) => (p === "/" ? p : p.replace(/\/$/, ""))
const canonical = (path: string) => `${siteConfig.url}${noSlash(path)}`
const count = (ks: readonly WorkbookKeyword[], f: (k: WorkbookKeyword) => boolean) => ks.filter(f).length
const kwRow = (k: WorkbookKeyword) => `| ${k.id} | ${k.keyword} | ${k.priority} | ${k.geography} |`

const HANDLING: Record<string, string> = {
  pricing: "Do not state or imply a price, range or 'cheap'. Cost content needs validated figures (owner decision D6).",
  "availability or response time": "Do not promise speed or 24-hour availability. Needs the operational basis in the page's availability item.",
  "superlative or quality": "Do not use best, top or quality wording. No evidence in the claims registry.",
  licensing: "Do not state or imply a licence or registration until C3 is closed.",
  "local presence or proximity": "Do not imply a nearby office until C2 and C6 are closed.",
}

function stats(path: string) {
  const ks = keywordsForPath(path)
  const held = ks.filter((k) => k.claimSensitive.length > 0)
  return { ks, held, p1: count(ks, (k) => k.priority === "P1"), p2: count(ks, (k) => k.priority === "P2"), p3: count(ks, (k) => k.priority === "P3"), tx: count(ks, (k) => k.intent === "Transactional") }
}

function renderBrief(b: ServiceBrief): string {
  const page = PLANNED_PAGES.find((p) => p.path === b.path)!
  const service = SERVICES.find((s) => s.id === b.serviceId)!
  const layer = PROTECTION_LAYERS.find((l) => l.id === b.layerId)!
  const { ks, held, p1, p2, tx } = stats(b.path)
  const usable = ks.filter((k) => k.claimSensitive.length === 0 && k.keyword.toLowerCase() !== page.primaryKeyword.toLowerCase())
  const head = usable.filter((k) => k.priority === "P1")
  const tail = usable.filter((k) => k.priority !== "P1")
  const L: string[] = []
  const w = (s = "") => L.push(s)

  w(`# ${b.rank}. ${service.name}: service page brief`)
  w()
  w(`Status: PLANNED, NOT PUBLISHED. No route exists for \`${b.path}\`; it is not in the sitemap or navigation. Generated by \`scripts/seo/build-service-docs.mjs\`; do not hand-edit.`)
  w()
  w("## Summary")
  w()
  w("| Item | Value |")
  w("|---|---|")
  w(`| Proposed URL (workbook) | \`${b.path}\` |`)
  w(`| Proposed canonical | \`${canonical(b.path)}\` (no trailing slash, matching the site's routing) |`)
  w(`| Implementation wave | ${b.wave} (roadmap ${b.roadmapWindow}) |`)
  w(`| Workbook page priority | ${page.priority} |`)
  w(`| Primary keyword | ${page.primaryKeyword} |`)
  w(`| Search intent | ${page.intent} (${tx} of ${ks.length} keywords). ${b.intentNote} |`)
  w(`| Keywords on the page | ${ks.length} (P1 ${p1}, P2 ${p2}); ${held.length} held back as claim-sensitive |`)
  w(`| Geographic variants | ${GEOS.map((g) => `${g} ${count(ks, (k) => k.geography === g)}`).join(", ")} |`)
  w(`| Existing service id | \`${service.id}\` (enquiry form preselect \`?service=${service.id}\`) |`)
  w()
  w("## Proposed metadata (draft, not live)")
  w()
  w("| Field | Proposed text | Length |")
  w("|---|---|---|")
  w(`| SEO title | ${esc(b.seoTitle)} | ${b.seoTitle.length} |`)
  w(`| Meta description | ${b.seoDescription} | ${b.seoDescription.length} |`)
  w(`| H1 | ${b.h1} | ${b.h1.length} |`)
  w()
  w("The title is the workbook PAGE MAP title with the approved brand. The description is built only from the primary keyword and the existing approved service description; it makes no licensing, availability, response-time, pricing or ranking claim. The workbook's draft description is not used because it contains unsupported wording.")
  w()
  w("## Keywords")
  w()
  w(`Primary: **${page.primaryKeyword}**. Supporting keywords below are usable in headings and body copy as topics. Geographic variants (Nairobi, Nakuru, Rongo, Migori) may be named only where C2 and C6 confirm that office provides the service.`)
  w()
  w(`### Priority supporting keywords (P1, ${head.length})`)
  w()
  w("| ID | Keyword | Priority | Geography |")
  w("|---|---|---|---|")
  for (const k of head) w(kwRow(k))
  w()
  w(`### Other supporting keywords (${tail.length})`)
  w()
  w("| ID | Keyword | Priority | Geography |")
  w("|---|---|---|---|")
  for (const k of tail) w(kwRow(k))
  w()
  w(`### Held back: claim-sensitive keywords (${held.length})`)
  w()
  if (held.length === 0) w("None on this page under the classifier in `lib/seo/claim-classifier.ts`.")
  else {
    w("| ID | Keyword | Category | Handling |")
    w("|---|---|---|---|")
    for (const k of held) w(`| ${k.id} | ${k.keyword} | ${k.claimSensitive.join(", ")} | ${k.claimSensitive.map((c) => HANDLING[c]).join(" ")} |`)
  }
  w()
  const scope = usable.filter((k) => SCOPE_TERMS.test(k.keyword))
  w(`### Scope-dependent keywords (${scope.length})`)
  w()
  if (scope.length === 0) w("None. No keyword on this page names an offering or setting beyond the existing site wording.")
  else {
    w("These name an offering or setting the existing site copy does not state. Use them only if this service's evidence items confirm it; otherwise leave them out of copy.")
    w()
    w("| ID | Keyword | Term to confirm |")
    w("|---|---|---|")
    for (const k of scope) w(`| ${k.id} | ${k.keyword} | ${k.keyword.match(SCOPE_TERMS)![0].toLowerCase()} |`)
  }
  w()
  w("## Page outline")
  w()
  w("The visual design is frozen. This outline is content structure only; layout needs owner approval (C11).")
  w()
  w("| # | Section | Purpose | Source |")
  w("|---|---|---|---|")
  b.outline.forEach((s, i) => w(`| ${i + 1} | ${s.heading} | ${s.purpose} | ${s.source} |`))
  w()
  w("## Existing approved wording")
  w()
  w("This is text already live on the site. It is approved site copy, not independently verified operational fact.")
  w()
  w("| Source | Wording |")
  w("|---|---|")
  w(`| lib/services.ts, ${service.name} | ${service.description} |`)
  w(`| lib/protection-layers.ts, ${layer.name} layer (${layer.services}) | ${layer.description} |`)
  w(`| lib/protection-layers.ts, ${layer.name} headline | ${layer.headline.lead} ${layer.headline.emphasis} |`)
  w()
  w("Photos: none may be shown. All entries in `lib/photo-library.ts` have pending rights clearance.")
  w()
  w("## Missing operational evidence")
  w()
  w("Common to every service page (full text in `evidence-and-approvals.md`):")
  w()
  w("| ID | Requirement | Owner | Blocks |")
  w("|---|---|---|---|")
  for (const e of COMMON_EVIDENCE) w(`| ${e.id} | ${e.requirement} | ${e.owner} | ${e.blocks} |`)
  w()
  w("Specific to this service:")
  w()
  w("| ID | Requirement | Owner | Blocks |")
  w("|---|---|---|---|")
  for (const e of b.serviceEvidence) w(`| ${e.id} | ${e.requirement} | ${e.owner} | ${e.blocks} |`)
  w()
  w("## Claims requiring approval")
  w()
  w("Claims-registry entries this page could be tempted to use. All are `needs-evidence` today and must not appear.")
  w()
  w("| Claim id | Registry text | Status |")
  w("|---|---|---|")
  for (const id of b.registryClaimIds) {
    const c = CLAIMS.find((x) => x.id === id)!
    w(`| ${c.id} | ${c.text} | ${c.status} |`)
  }
  w()
  w("Wording found elsewhere that must not be reused on this page without evidence:")
  w()
  w("| Wording | Where |")
  w("|---|---|")
  for (const l of b.legacyWording) w(`| ${l.wording} | ${l.where} |`)
  w()
  w("## Suggested internal links")
  w()
  w("| Link target | Anchor text | Status | Note |")
  w("|---|---|---|---|")
  for (const l of b.internalLinks) w(`| \`${l.to}\` | ${l.anchor} | ${l.status} | ${l.note} |`)
  w()
  return L.join("\n")
}

function renderPlan(): string {
  const L: string[] = []
  const w = (s = "") => L.push(s)
  w("# Service page implementation plan (Milestone 5B.1)")
  w()
  w("Generated by `scripts/seo/build-service-docs.mjs` from `Jolu_Security_SEO_Keyword.xlsx` (via `lib/seo/workbook-keywords.ts`) and the typed specs in `lib/seo/service-briefs.ts`. Do not hand-edit.")
  w()
  w("Status: PREPARATION ONLY. No service page, route, sitemap entry or navigation change exists. Publishing needs the evidence in `evidence-and-approvals.md` and the owner's approval.")
  w()
  w("## Documents")
  w()
  w("- `implementation-plan.md` (this file): priorities, sequence, audit of existing wording.")
  for (const b of SERVICE_BRIEFS) w(`- \`${briefFileName(b)}\`: ${SERVICES.find((s) => s.id === b.serviceId)!.name}`)
  w("- `evidence-and-approvals.md`: evidence, claims, discrepancies, owner decisions.")
  w("- `page-architecture.md`: reusable page architecture for the Next.js application.")
  w("- `publishing-checklist.md`: acceptance checklist for publishing one page.")
  w()
  w("## How the priority was decided")
  w()
  w("Rank is set by, in order, using only workbook evidence:")
  w()
  w("1. PAGE MAP & META priority (P1 before P2).")
  w("2. 90 DAY ROADMAP window (Week 3 for manned guarding, CCTV and electric fencing; Weeks 6-7 for events, K9, alarm response and VIP).")
  w("3. Number of P1 keywords mapped to the page in KEYWORD MASTER (more first).")
  w("4. PAGE MAP row order, where the first three tie (K9, alarm response, VIP).")
  w()
  w("No search volume, difficulty, CPC or ranking is used: the workbook marks all of them Not validated. The P1 counts per cluster in the CLUSTER STRATEGY sheet equal the P1 counts used here. Readiness is reported separately and does not change the rank.")
  w()
  w("## Priority table")
  w()
  w("| Rank | Page | Wave | Page priority | Roadmap | Keywords | P1 | P2 | Held (claim-sensitive) | Publication-blocking service items |")
  w("|---|---|---|---|---|---|---|---|---|---|")
  for (const b of SERVICE_BRIEFS) {
    const page = PLANNED_PAGES.find((p) => p.path === b.path)!
    const s = stats(b.path)
    const blocking = b.serviceEvidence.filter((e) => e.blocks === "publication").length
    w(`| ${b.rank} | \`${b.path}\` | ${b.wave} | ${page.priority} | ${b.roadmapWindow} | ${s.ks.length} | ${s.p1} | ${s.p2} | ${s.held.length} | ${blocking} |`)
  }
  w()
  w("## Sequence")
  w()
  const wave1 = SERVICE_BRIEFS.filter((b) => b.wave === 1).map((b) => stats(b.path))
  const all = SERVICE_BRIEFS.map((b) => stats(b.path))
  const sum = (xs: { ks: readonly unknown[] }[]) => xs.reduce((n, x) => n + x.ks.length, 0)
  const sumP1 = (xs: { p1: number }[]) => xs.reduce((n, x) => n + x.p1, 0)
  const alarm = stats("/services/alarm-response/")
  w(`**Wave 1 (roadmap Week 3): manned guarding, CCTV installation, electric fencing.** These are the three P1 pages. Together they hold ${sum(wave1)} of the ${sum(all)} service keywords and ${sumP1(wave1)} of the ${sumP1(all)} service P1 keywords.`)
  w()
  w(`**Wave 2 (roadmap Weeks 6-7): events security, K9 unit, alarm response, VIP close protection.** Alarm response has the heaviest claim burden: ${alarm.held.length} of its ${alarm.ks.length} keywords promise speed or 24-hour availability, and its response model (item AR1) blocks publication. Plan it last in the wave unless Operations can document its response model sooner.`)
  w()
  w("Before any page starts: close the shared items C1, C2, C7, C8, C9, C10 and C11 for that page, answer owner decisions D1 to D4, and keep the Blog noindex. Wave 2 can begin in parallel once Wave 1 proves the page architecture.")
  w()
  w("## Audit of existing service wording")
  w()
  w("The live site describes each service in one sentence plus a protection-layer line. This is all the approved wording that exists; the briefs use nothing else.")
  w()
  w("| Service id | Name | Existing description | Layer | Slug in workbook |")
  w("|---|---|---|---|---|")
  for (const b of SERVICE_BRIEFS) {
    const s = SERVICES.find((x) => x.id === b.serviceId)!
    const layer = PROTECTION_LAYERS.find((l) => l.id === b.layerId)!
    w(`| \`${s.id}\` | ${s.name} | ${s.description} | ${layer.name} | \`${b.path}\` |`)
  }
  w()
  w("Findings:")
  w()
  w("- Each service has one sentence of copy. That is not enough to build a useful, non-thin page; every brief therefore needs owner-supplied scope (C1, C2).")
  w("- The K9 service id is `k9-unit` but the workbook slug is `k9-unit-services`. Keep the id for the enquiry form and use the workbook slug for the URL.")
  w("- Workbook URLs end with a slash. The site's routing has no trailing slash, so canonical, sitemap and links must all use the slash-less form (see `page-architecture.md`).")
  w("- The protection layers file states its headlines are visual framing, not claims. 'Every alarm, answered.' still reads as a promise and is flagged on the alarm brief.")
  w("- No photo may be shown: every entry in `lib/photo-library.ts` has pending clearance.")
  w("- The downloadable company profile and brochure conflict with the site in several ways (evidence document, section 4).")
  w()
  return L.join("\n")
}

function renderEvidence(): string {
  const L: string[] = []
  const w = (s = "") => L.push(s)
  w("# Evidence and approval requirements")
  w()
  w("Generated by `scripts/seo/build-service-docs.mjs`. Do not hand-edit. Nothing here has been verified with the business; every item is an open requirement.")
  w()
  w("## 1. Evidence common to every service page")
  w()
  w("| ID | Requirement | Owner | Blocks |")
  w("|---|---|---|---|")
  for (const e of COMMON_EVIDENCE) w(`| ${e.id} | ${e.requirement} | ${e.owner} | ${e.blocks} |`)
  w()
  w("Blocks: publication means the page cannot go live without it; claim means only the statements that rely on it are blocked; section means only that page section is left out.")
  w()
  w("## 2. Evidence specific to each service")
  w()
  for (const b of SERVICE_BRIEFS) {
    w(`### ${SERVICES.find((s) => s.id === b.serviceId)!.name}`)
    w()
    w("| ID | Requirement | Owner | Blocks |")
    w("|---|---|---|---|")
    for (const e of b.serviceEvidence) w(`| ${e.id} | ${e.requirement} | ${e.owner} | ${e.blocks} |`)
    w()
  }
  w("## 3. Claims requiring approval")
  w()
  w("### Claims registry (lib/claims.ts)")
  w()
  w("| Claim id | Text | Status | Service pages that would use it |")
  w("|---|---|---|---|")
  for (const c of CLAIMS) {
    const users = SERVICE_BRIEFS.filter((b) => b.registryClaimIds.includes(c.id)).map((b) => b.serviceId)
    w(`| ${c.id} | ${c.text} | ${c.status} | ${users.length === SERVICE_BRIEFS.length ? "all" : users.join(", ") || "none"} |`)
  }
  w()
  w("### Held keywords on service pages")
  w()
  w("| ID | Keyword | Page | Category |")
  w("|---|---|---|---|")
  for (const b of SERVICE_BRIEFS) for (const k of stats(b.path).held) w(`| ${k.id} | ${k.keyword} | \`${b.path}\` | ${k.claimSensitive.join(", ")} |`)
  w()
  w("These keywords stay mapped to their pages as topics, but their wording must not appear until the matching claim is approved. Handling rules are in each brief.")
  w()
  w("## 4. Discrepancies between the website and the downloadable documents")
  w()
  w(`The site links two PDFs (\`${siteConfig.downloads.map((d) => d.href).join("`, `")}\`) from its downloads list. Both were reviewed read-only. They are not used as evidence, and they are not changed here.`)
  w()
  w("| Topic | Website (lib/site-config.ts) | company-profile.pdf / brochure.pdf |")
  w("|---|---|---|")
  w(`| Company name | ${siteConfig.name}; approved brand JOLU SECURITY | Jolu Group Ltd Security / Jolu Group Security Ltd |`)
  w(`| Nairobi office | ${siteConfig.offices[0].address} | Head office at Thome Estate; P.O. Box 7161-00200 |`)
  w(`| Nakuru office | ${siteConfig.offices[1].address} | KFA Building, along Geoffrey Kamau Avenue |`)
  w(`| Other offices | ${siteConfig.offices[2].address} (Migori) | Branches listed as Eldoret, Migori and Kisumu |`)
  w(`| Phone numbers | ${siteConfig.contact.primaryPhone.display} and ${siteConfig.contact.phones[1].display} | +254 790 298 003 and +254 769 281 518 |`)
  w("| Claims | Registry: all needs-evidence | 24/7 availability, immediate response, highly trained, state-of-the-art, international operations, detection of explosives or narcotics, bouncer services, compliance with international regulations |")
  w("| Services | Seven services | Also cleaning, gardening, labour and other services not on the website |")
  w()
  w("The website, not the PDFs, is the approved source for this work. The owner must decide which is authoritative (decision D1).")
  w()
  w("## 5. Owner decisions required")
  w()
  w("| ID | Decision | Why it matters |")
  w("|---|---|---|")
  w("| D1 | Which source is authoritative for offices, branches, phone numbers and company name: the website or the PDFs? Keep, correct or withdraw the live PDF downloads. | The PDFs contradict the website and make unapproved claims on a live page. |")
  w("| D2 | Approve the order: Wave 1 manned guarding, CCTV, electric fencing; Wave 2 events, K9, alarm response, VIP. Or reorder. | Sets the first page to build. |")
  w("| D3 | May service pages reuse existing components, and may the homepage cards and footer links point to them? | The design is frozen; no layout has been approved. |")
  w("| D4 | Which services each office provides (Nairobi, Nakuru, Rongo). | Gates every geographic keyword variant and any location wording. |")
  w("| D5 | Who is the compliance reviewer, and which PSRA registration or licence applies to each service. Is licensing wording wanted at all? | Licensing statements are blocked until then. |")
  w("| D6 | Whether to publish cost content. Default is no pricing anywhere. | Needs validated ranges before any cost keyword is used. |")
  w("| D7 | Which legacy offerings are real: CCTV monitoring, K9 detection, bouncer services, 24/7 alarm response. | The site offers none of these today. |")
  w("| D8 | Keep or revise the existing layer headlines, notably 'Every alarm, answered.' | It reads as a promise; it is existing approved copy and is not changed here. |")
  w("| D9 | Confirm the legacy 'other services' (labour, cleaning and similar) stay out of scope. | They are not on the website or in the workbook. |")
  w("| D10 | Provide rights-cleared service photos. | Every photo in the registry is pending. |")
  w()
  return L.join("\n")
}

function renderChecklist(): string {
  const L: string[] = []
  const w = (s = "") => L.push(s)
  w("# Publishing acceptance checklist")
  w()
  w("Generated by `scripts/seo/build-service-docs.mjs`. Do not hand-edit. Use once per service page. A page is accepted only when every row is checked with its proof attached to the pull request.")
  w()
  w("| Done | Area | Check | Source | Proof |")
  w("|---|---|---|---|---|")
  for (const c of PUBLISHING_CHECKLIST) w(`| [ ] | ${c.area} | ${c.check} | ${c.source} | ${c.proof} |`)
  w()
  return L.join("\n")
}

export function renderServiceDocs(): Record<string, string> {
  const files: Record<string, string> = {
    "implementation-plan.md": renderPlan(),
    "evidence-and-approvals.md": renderEvidence(),
    "publishing-checklist.md": renderChecklist(),
  }
  for (const b of SERVICE_BRIEFS) files[briefFileName(b)] = renderBrief(b)
  return files
}

