// Regenerates docs/assets/inventory.{json,md}. Run: node scripts/assets/build-inventory.mjs
// Served rows are hashed from public/. Withheld originals are NOT in the repository: their rows come from the
// hash-only manifest (docs/assets/WITHHELD-MANIFEST.sha256) and carry no names or paths.
// Classification records TYPE only (never identities). Photos of people are uncleared unless the registry
// (lib/photo-library.ts) marks all four criteria approved/evidenced; currently none are.
import { readFileSync, statSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { BRAND_ALLOWLIST, WITHHELD_MANIFEST, sha256, walk } from "./asset-rules.mjs"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..")
const photoSrc = readFileSync(path.join(root, "lib/photo-library.ts"), "utf8")
const registry = new Map() // original relative path (under lovable-uploads) -> registry id
for (const m of photoSrc.matchAll(/id: "([^"]+)",\s*src: `\$\{BASE\}\/([^`]+)`/g)) registry.set(m[2], m[1])
const docSrc = readFileSync(path.join(root, "lib/document-library.ts"), "utf8")
for (const m of docSrc.matchAll(/id: "([^"]+)",\s*label: "[^"]+",\s*href: "\/cleared\/docs\/([^"]+)"/g)) registry.set(m[2], `doc:${m[1]}`)

// code references (app, components, lib, scripts, tests excluded from consumers except as noted)
const codeFiles = ["app", "components", "lib", "scripts"].flatMap((d) => walk(path.join(root, d)).map((f) => `${d}/${f}`)).filter((f) => /\.(ts|tsx|mjs|js|css)$/.test(f) && !f.startsWith("scripts/assets/"))
const codeText = codeFiles.map((f) => [f, readFileSync(path.join(root, f), "utf8")])
const referencedBy = (needle) => codeText.filter(([f, t]) => f !== "lib/photo-library.ts" && f !== "lib/document-library.ts" && t.includes(needle)).map(([f]) => f)
const legacyText = (() => { try { return readFileSync(path.join(root, "legacy-static/index.html"), "utf8") } catch { return "" } })()

const rows = []
for (const f of walk(path.join(root, "public"))) {
  const [type, sensitivity] = f.startsWith("lovable-uploads/") ? ["logo (company mark, illustration)", "none"] : [f === "placeholder.svg" ? "generic placeholder graphic" : "framework icon (Next.js template)", "none"]
  rows.push({ original: `public/${f}`, status: "SERVED (allowlisted brand/framework asset)", sizeBytes: statSync(path.join(root, "public", f)).size, sha256: sha256(path.join(root, "public", f)), pinnedInAllowlist: BRAND_ALLOWLIST[f] === sha256(path.join(root, "public", f)), type, sensitivity, clearance: "n/a (company mark / template asset)", referencedByCodeOutsideRegistry: [...codeText.filter(([cf, t]) => cf !== "lib/photo-library.ts" && cf !== "lib/document-library.ts" && t.includes(`/${f}`)).map(([cf]) => cf)].sort() })
}
const KIND = { "staff-portrait": ["people photo (staff portrait)", "highest"], "document-pdf": ["document (PDF)", "high"], "page-image": ["document (brochure page image showing people)", "high"], "people-photo": ["people photo", "high"], "place-or-stock-photo": ["stock/illustration or place photo (some show hands or a person partially)", "medium"] }
const withheld = []
for (const line of readFileSync(path.join(root, WITHHELD_MANIFEST), "utf8").split("\n").filter((l) => l && !l.startsWith("#"))) {
  const [hash, index, kind] = line.split(/ {2}/)
  const [type, sensitivity] = KIND[kind] ?? ["unclassified", "high"]
  withheld.push({ index, sha256: hash, kind, type, sensitivity, status: "WITHHELD (original not in this repository; uncleared)", clearance: "UNCLEARED" })
}
rows.sort((a, b) => a.original.localeCompare(b.original))
const all = [...rows, ...withheld]
const bySha = new Map(); for (const r of all) bySha.set(r.sha256, [...(bySha.get(r.sha256) ?? []), r.original ?? r.index])
const duplicates = [...bySha.values()].filter((x) => x.length > 1)

writeFileSync(path.join(root, "docs/assets/inventory.json"), JSON.stringify({ generatedBy: "scripts/assets/build-inventory.mjs", baseCommit: "9e8e742", servedFiles: rows.length, withheldFiles: withheld.length, duplicates, served: rows, withheld }, null, 2) + "\n")

const kb = (n) => (n / 1024).toFixed(0)
const md = [
  "# Public asset inventory", "",
  `Generated by \`scripts/assets/build-inventory.mjs\` (base commit 9e8e742). ${rows.length} served files and ${withheld.length} withheld files. Full data: \`inventory.json\`.`, "",
  "Rules: type classification only (no identities, names or original paths recorded). Everything not approved in `lib/photo-library.ts` / `lib/document-library.ts` is uncleared; zero entries are approved. Withheld originals are not in this repository; they are listed only by SHA-256 and neutral index (see `README.md`).", "",
  "## Served", "",
  "| Path | Size KB | Type | Code refs (outside registry) | sha256 |", "|---|---:|---|---|---|",
  ...rows.map((r) => `| ${r.original} | ${kb(r.sizeBytes)} | ${r.type} | ${r.referencedByCodeOutsideRegistry.join(", ") || "none"} | \`${r.sha256}\` |`),
  "", "## Withheld (hash-only)", "", "| Index | Kind | Sensitivity | Clearance | sha256 |", "|---|---|---|---|---|",
  ...withheld.map((r) => `| ${r.index} | ${r.type} | ${r.sensitivity} | ${r.clearance} | \`${r.sha256}\` |`),
  "", "## Byte-identical duplicates", "", ...(duplicates.length ? duplicates.map((d) => `- ${d.join(" = ")}`) : ["none"]), "",
].join("\n")
writeFileSync(path.join(root, "docs/assets/inventory.md"), md)
console.log(`inventory: ${rows.length} served, ${withheld.length} withheld`)
