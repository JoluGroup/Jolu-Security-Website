// Renders the Business Verification Pack documents from the typed data. DOCUMENTATION ONLY.
import { ITEMS_ALL, ROLES, PAGES, ALL, SECTION_ORDER, CATEGORIES, STATUSES, pageByCode, itemById, CLAIM_RISKS, LEGACY_WORDING } from "./items.mjs"
import { SOURCES, DECISIONS, QUESTIONS, CONFLICTS, SINGLE_SOURCE, CORRECTIONS, PREPARED, READINESS_STATUS, APPROVERS, LOCATION_CLAIM_RISKS, questionPages } from "./data.mjs"

const GEN = "<!-- Generated by scripts/seo/business-verification/build.mjs. Do not edit by hand: change the data module and rebuild. -->"
const esc = (s) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ")
const table = (head, rows) => [`| ${head.join(" | ")} |`, `| ${head.map(() => "---").join(" | ")} |`, ...rows.map((r) => `| ${r.map(esc).join(" | ")} |`)].join("\n")
const pagesLabel = (codes) => (codes.length === ALL.length ? "All 10" : codes.join(", "))
const count = (arr, f) => arr.reduce((a, x) => ((a[f(x)] = (a[f(x)] || 0) + 1), a), {})
const pageName = (c) => `${c} ${pageByCode(c).name}`
const sha7 = (s) => s.slice(0, 7)

