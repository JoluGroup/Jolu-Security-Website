function registerRow(i) {
  return [i.id, i.question, i.source, i.current, i.conflict || "None", i.required, ROLES[i.role], i.status, i.priority, pagesLabel(i.pages), `${i.impact}${i.impactNote ? ": " + i.impactNote : ""}`]
}
export function renderRegister() {
  const byStatus = count(ITEMS_ALL, (i) => i.status)
  const sections = SECTION_ORDER.map((cat) => {
    const items = ITEMS_ALL.filter((i) => i.category === cat)
    return `## ${CATEGORIES[cat]} (${items.length})\n\n${table(["ID", "Business question", "Current source", "Current information", "Conflicting information", "Evidence required", "Responsible role", "Status", "Priority", "Affected pages", "Publication impact"], items.map(registerRow))}`
  })
  return `${GEN}
# Evidence Register

${ITEMS_ALL.length} items. Prepared ${PREPARED}. Page codes: ${PAGES.map((p) => `${p.code} ${p.name}`).join("; ")}.

${table(["Status", "Items"], STATUSES.map((s) => [s, byStatus[s] || 0]))}

Approved public copy is shown as such: it is the website's own text, not proof. Items whose source is "None" were searched for in the website configuration, the claims registry, both PDFs and the workbook.

${sections.join("\n\n")}
`
}

export function renderQuestionnaire() {
  const roleBlocks = Object.entries(ROLES).map(([key, label]) => {
    const qs = QUESTIONS.filter((q) => q.role === key)
      .map((q) => ({ q, pages: questionPages(q) }))
      .sort((a, b) => b.pages.length - a.pages.length || a.q.id.localeCompare(b.q.id))
    return `## ${label} (${qs.length} questions)\n\n${table(["Ref", "Question", "Pages it can unblock", "Evidence items", "Answer / document supplied"], qs.map(({ q, pages }) => [q.id, q.question, pages.length ? pagesLabel(pages) : "Decision only", q.items.length ? q.items.join(", ") : q.decisions.join(", "), ""]))}`
  })
  const open = DECISIONS.filter((d) => d.status !== "DECIDED")
  return `${GEN}
# Management Questionnaire

For JOLU management. ${QUESTIONS.length} questions in five groups. Within each group the questions that unblock the most pages come first. Each question appears once; the evidence items it settles are listed so nothing is asked twice.

How to answer: write the answer or name the document in the last column, or reply with the reference (for example Q-OPS-01) and the answer. Do not send passwords. Where a question asks for a document, a clear photo or scan is enough.

${roleBlocks.join("\n\n")}

## Decision record

Management completes this section. Each row is a decision the pack needs; nothing is pre-filled. "Proposed" rows are recommendations awaiting your answer, not decisions.

${table(["Ref", "Decision needed", "Status", "Decision (approve / reject / change)", "Decided by", "Date", "Notes"], open.map((d) => [d.id, d.title, d.status, "", "", "", ""]))}
`
}

const SERVICE_PAGES = PAGES.filter((p) => p.kind === "service")
export function pageRequirements(p) {
  const items = ITEMS_ALL.filter((i) => i.pages.includes(p.code))
  const gating = items.filter((i) => i.impact === "BLOCKS PUBLICATION")
  return { items, gating, claims: items.filter((i) => i.impact === "BLOCKS CLAIM"), sections: items.filter((i) => i.impact === "BLOCKS SECTION") }
}
function usable(p) {
  if (p.kind === "service") {
    const id = p.key
    const svc = ITEMS_ALL.find((i) => i.id === ITEMS_ALL.find((x) => x.category === "SVC" && x.pages[0] === p.code && x.id.endsWith("-01")).id)
    return `${svc.current.split(" Layer line")[0]}`
  }
  const o = { nairobi: "NBO", nakuru: "NAK", rongo: "RON" }[p.key]
  const n = ITEMS_ALL.find((i) => i.id === `OFF-${o}-02`)
  return `Office name and address as approved public copy. ${n.current}`
}
export function renderReadiness() {
  const sum = table(["Page", "Path", "Wave", "Blocking items", "Conflicts", "Status"], PAGES.map((p) => {
    const r = pageRequirements(p)
    return [pageName(p.code), p.path, p.wave, r.gating.length, r.items.filter((i) => i.status === "CONFLICTED").length, READINESS_STATUS]
  }))
  const blocks = PAGES.map((p) => {
    const r = pageRequirements(p)
    const conflicts = r.items.filter((i) => i.status === "CONFLICTED")
    const missing = r.gating.filter((i) => i.status === "MISSING" || i.status === "PROVISIONAL" || i.status === "CONFLICTED")
    const risks = p.kind === "service" ? CLAIM_RISKS[p.key] : LOCATION_CLAIM_RISKS[p.key]
    const approver = p.kind === "service" ? APPROVERS.service : APPROVERS.location
    const own = r.items.filter((i) => i.pages.length === 1)
    return `### ${pageName(p.code)}

${table(["Field", "Detail"], [
      ["Path (planned, not created)", p.path],
      ["Publication status", `**${READINESS_STATUS}**`],
      ["Existing usable content", `${usable(p)} This is approved public copy only; nothing here is independently verified.`],
      ["Required evidence (blocks publication)", r.gating.map((i) => i.id).join(", ")],
      ["Missing evidence", missing.filter((i) => i.status === "MISSING").map((i) => i.id).join(", ") || "None"],
      ["Provisional only", missing.filter((i) => i.status === "PROVISIONAL").map((i) => i.id).join(", ") || "None"],
      ["Conflicting information", conflicts.map((i) => i.id).join(", ") || "None"],
      ["Claim risks", risks],
      ["Claims and sections also gated", `${r.claims.length} claim items, ${r.sections.length} section items (see the register)`],
      ["Responsible approver", approver],
      ["Written approval to publish", "Not given"],
    ])}`
  })
  return `${GEN}
# Publication Readiness Matrix

All ten planned pages are **${READINESS_STATUS}**. A page changes status only when every item in its "Required evidence" row is VERIFIED, its conflicts are resolved by management, its claims are approved in the claims registry, and the approver has signed. No page is ready today and none is created by this pack.

${sum}

${blocks.join("\n\n")}

## Shared blockers

${table(["Evidence item", "Question", "Status", "Pages blocked"], ITEMS_ALL.filter((i) => i.impact === "BLOCKS PUBLICATION" && i.pages.length >= 5).map((i) => [i.id, i.question, i.status, pagesLabel(i.pages)]))}

Companion documents: docs/seo/service-pages/ and docs/seo/location-pages/ on the preparation branches (PR #5, PR #6).
`
}

